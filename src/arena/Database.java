package arena;
import java.sql.*;
import java.nio.file.*;
/** Relational storage via JDBC: local H2 or hosted PostgreSQL. */
public final class Database {
 private final String url;
 private final String user,password;
 private final boolean postgres;
 public Database(Path file)throws Exception{
  this(file,System.getenv());
 }
 Database(Path file,java.util.Map<String,String> env)throws Exception{
  String remote=env.getOrDefault("JDBC_DATABASE_URL", "").trim();
  postgres=!remote.isEmpty();
  if(postgres){
   if(!remote.startsWith("jdbc:postgresql://"))throw new IllegalArgumentException("JDBC_DATABASE_URL must start with jdbc:postgresql://");
   url=remote;user=env.getOrDefault("DB_USER", "");password=env.getOrDefault("DB_PASSWORD", "");
   if(user.isBlank()||password.isBlank())throw new IllegalArgumentException("Set DB_USER and DB_PASSWORD for PostgreSQL");
   Class.forName("org.postgresql.Driver");
  }else{
   if("true".equalsIgnoreCase(env.get("REQUIRE_POSTGRES")))throw new IllegalArgumentException("Set JDBC_DATABASE_URL, DB_USER and DB_PASSWORD before deploying");
   Files.createDirectories(file.toAbsolutePath().getParent());
   Class.forName("org.h2.Driver");url="jdbc:h2:file:"+file.toAbsolutePath()+";DB_CLOSE_ON_EXIT=FALSE";user="sa";password="";
  }
  try(var c=open();var s=c.createStatement()){
   s.execute("CREATE TABLE IF NOT EXISTS users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(24) UNIQUE NOT NULL, password_hash VARCHAR(300) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
   s.execute("CREATE TABLE IF NOT EXISTS challenges(id VARCHAR(30) PRIMARY KEY, game_type VARCHAR(12) NOT NULL, level INT NOT NULL, title VARCHAR(80) NOT NULL, UNIQUE(game_type,level))");
   s.execute("CREATE TABLE IF NOT EXISTS attempts(id VARCHAR(40) PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), challenge_id VARCHAR(30) NOT NULL REFERENCES challenges(id), started_at BIGINT NOT NULL, step_index INT DEFAULT 0 NOT NULL, correct_count INT DEFAULT 0 NOT NULL, score INT DEFAULT 0 NOT NULL, elapsed_seconds INT DEFAULT 0 NOT NULL, completed BOOLEAN DEFAULT FALSE NOT NULL)");
   s.execute("CREATE TABLE IF NOT EXISTS answers(attempt_id VARCHAR(40) NOT NULL REFERENCES attempts(id), step_index INT NOT NULL, submitted VARCHAR(100) NOT NULL, correct BOOLEAN NOT NULL, PRIMARY KEY(attempt_id,step_index))");
   s.execute("CREATE INDEX IF NOT EXISTS attempts_user_idx ON attempts(user_id)");
  }
  try(var c=open();var p=c.prepareStatement(postgres?"INSERT INTO challenges(id,game_type,level,title) VALUES(?,?,?,?) ON CONFLICT(id) DO UPDATE SET game_type=EXCLUDED.game_type,level=EXCLUDED.level,title=EXCLUDED.title":"MERGE INTO challenges(id,game_type,level,title) KEY(id) VALUES(?,?,?,?)")){
   for(var d:ChallengeFactory.catalog()){p.setString(1,d.get("type")+"-"+d.get("level"));p.setString(2,(String)d.get("type"));p.setInt(3,(int)d.get("level"));p.setString(4,(String)d.get("title"));p.addBatch();}p.executeBatch();
  }
 }
 public Connection open()throws SQLException{return DriverManager.getConnection(url,user,password);}
}
